def reading(text: str) -> str:
    value = "".join(token.reading if token.reading != "*" else token.surface for token in TOKENIZER.tokenize(text))
    return "".join(chr(ord(char) - 0x60) if "ァ" <= char <= "ヶ" else char for char in value)

def roma(text: str) -> str:
    return " ".join(piece["hepburn"] for piece in KAKASI.convert(text))

def write(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    json.loads(path.read_text(encoding="utf-8"))

def main():
    shells = json.loads((TIMING / "frame-shells.json").read_text(encoding="utf-8"))["frames"]
    frames = []
    for shell in shells:
        cards = []
        annotations = []
        for item in ANALYSIS[shell["id"]]:
            value = dict(item)
            value.update({"reading": reading(value["token"]), "romaji": roma(value["token"]), "status": "draft", "fieldProvenance": "assisted phrase-level draft; Janome 0.5.0 reading; pykakasi 2.3.0 romaji"})
            if value["token"] in {"フィロソフィー", "シルエットダンス", "リンク", "ビート", "リアリティー", "メロディライン", "リズム", "ダンス", "リセット", "クラウド"}:
                value["sourceWord"] = {"フィロソフィー":"philosophy", "シルエットダンス":"silhouette dance", "リンク":"link", "ビート":"beat", "リアリティー":"reality", "メロディライン":"melody line", "リズム":"rhythm", "ダンス":"dance", "リセット":"reset", "クラウド":"cloud"}[value["token"]]
            cards.append(value)
            annotations.append({"token": value["token"], "reading": value["reading"]})
        frame = dict(shell)
        frame["caption"] = dict(shell["caption"], furigana=annotations, translationStatus="draft-qmts-source")
        frame["grammarCards"] = cards
        frame["status"] = "draft-needs-human-review"
        frames.append(frame)
    write(PROJECT / "frames.json", {"schemaVersion": 2, "frames": frames})
    table = {"の":"所属／修饰", "が":"主语标记", "を":"动作对象／经过范围", "に":"到达处／作用对象", "で":"状态／手段／条件", "と":"共同／重叠对象", "は":"主题提示", "も":"添加、强调或让步"}
    write(PROJECT / "review" / "particle-functions.json", {"schemaVersion": 1, "functions": table})

if __name__ == "__main__": main()
